/**
 * 발표 시연용 GPS 경로 재생기 — 브라우저 콘솔에 붙여넣어 쓴다.
 *
 * 왜 있나 — 발표장은 탄천이 아니라서, 실제로 달려서는 「총 거리」와 「탄천 인정 거리」가 갈리는
 * 장면을 보여 줄 수 없다. 이 스니펫은 **브라우저의 위치 API 만** 미리 만든 경로로 바꾼다.
 * 앱은 평소와 똑같이 동작한다.
 *
 * 하지 않는 것
 * - **DB 에 직접 쓰지 않는다.** 저장은 앱의 정상 경로(측정 → 업로드 → 종료 2단계)로만 된다
 * - 거리 · Zone 판정을 손대지 않는다. 판정은 그대로 `src/domain/measure` 가 한다
 * - 좌표를 손으로 찍지 않았다. `src/domain/measure/zone.ts` 의 Zone 폴리곤에서 중심선을 복원해
 *   계산했고, 점 간격은 20km/h(3'00"/km)로 1초에 하나다 — P9 상한 25km/h 아래다
 *
 * 쓰는 법
 *   1. 배포 링크에 로그인하고 홈(달리기 탭)을 연다
 *   2. F12 → Console 에 이 파일 전체를 붙여넣고 Enter
 *      (화면이 랭킹 탭에 잠깐 갔다 홈으로 돌아온다 — 아래 「탭 한 바퀴」 주석 참고)
 *   3. GPS 가 준비되면 「러닝 시작하기」
 *   4. 약 47초 뒤 `구역 내` → `구역 밖` 으로 바뀌고 **인정 거리만 멈춘다**
 *   5. 1분 7초면 경로가 끝난다. 「밀어서 러닝 종료」
 *
 * 경로: 성남 야탑동 탄천 · 67점 · 총 0.37km · 탄천 인정 0.26km
 */
(function () {
  /** [위도, 경도] · 1초에 한 점. 앞 47점이 Zone 안, 나머지가 Zone 밖이다. */
  var POINTS = [
    [37.409835,127.123199], [37.409884,127.123186], [37.409933,127.123173], [37.409981,127.123159],
    [37.41003,127.123146], [37.410079,127.123133], [37.410128,127.123119], [37.410177,127.123106],
    [37.410225,127.123093], [37.410274,127.123079], [37.410323,127.123066], [37.410372,127.123053],
    [37.410421,127.123039], [37.41047,127.123026], [37.410518,127.123013], [37.410567,127.122999],
    [37.410616,127.122986], [37.410665,127.122973], [37.410714,127.122959], [37.410763,127.122946],
    [37.410811,127.122933], [37.41086,127.122919], [37.410871,127.122981], [37.410881,127.123042],
    [37.410892,127.123104], [37.410903,127.123165], [37.410913,127.123227], [37.410924,127.123288],
    [37.410934,127.12335], [37.410945,127.123411], [37.410956,127.123472], [37.410966,127.123534],
    [37.410977,127.123595], [37.410987,127.123657], [37.410998,127.123718], [37.411009,127.12378],
    [37.411019,127.123841], [37.41103,127.123903], [37.41104,127.123964], [37.411051,127.124026],
    [37.411062,127.124087], [37.411072,127.124149], [37.411083,127.12421], [37.411093,127.124272],
    [37.411104,127.124333], [37.411114,127.124395], [37.411125,127.124456], [37.411136,127.124517],
    [37.411146,127.124579], [37.411157,127.12464], [37.411167,127.124702], [37.411178,127.124763],
    [37.411189,127.124825], [37.411199,127.124886], [37.41121,127.124948], [37.41122,127.125009],
    [37.411231,127.125071], [37.411242,127.125132], [37.411252,127.125194], [37.411263,127.125255],
    [37.411273,127.125317], [37.411284,127.125378], [37.411295,127.12544], [37.411305,127.125501],
    [37.411316,127.125562], [37.411326,127.125624], [37.411337,127.125685]
  ];
  var INTERVAL_MS = 1000;

  // 이미 켜져 있으면 처음으로 되돌리기만 한다(두 번 붙여넣어도 안전하다).
  if (window.__tancheonDemo) {
    window.__tancheonDemo.reset();
    console.log("[탄천런 시연] 경로를 처음으로 되돌렸습니다.");
    return;
  }

  var i = 0;

  function fix() {
    var p = POINTS[Math.min(i, POINTS.length - 1)];
    return {
      coords: {
        latitude: p[0],
        longitude: p[1],
        accuracy: 6,
        altitude: null,
        altitudeAccuracy: null,
        heading: null,
        speed: null,
      },
      timestamp: Date.now(),
    };
  }

  /*
    오류 콜백은 **절대 부르지 않는다.** 한 번이라도 부르면 앱이 GPS 유실로 보고 새 segment 를
    시작해 구간이 만들어지지 않는다 — 거리가 0.00 에서 안 올라간다.
  */
  var player = {
    getCurrentPosition: function (ok) {
      setTimeout(function () {
        ok(fix());
      }, 0);
    },
    watchPosition: function (ok) {
      setTimeout(function () {
        ok(fix());
      }, 0);
      return setInterval(function () {
        if (i < POINTS.length - 1) i++;
        ok(fix());
      }, INTERVAL_MS);
    },
    clearWatch: function (id) {
      clearInterval(id);
    },
  };
  Object.defineProperty(navigator, "geolocation", { value: player, configurable: true });

  /*
    탭 한 바퀴 — 이 스니펫을 넣을 때쯤 홈은 이미 측위를 시작해 「GPS 확인 중」에 매달려 있다.
    앱 안의 링크로 랭킹 → 달리기를 다녀오면 **같은 문서에서** 홈이 다시 뜨고 이 재생기로 다시
    측위한다. 새로고침(F5)을 하면 이 주입이 사라지므로 하지 않는다.
  */
  if (location.pathname === "/home") {
    setTimeout(function () {
      var toRanking = document.querySelector('a[href="/ranking"]');
      if (!toRanking) return;
      toRanking.click();
      setTimeout(function () {
        var toHome = document.querySelector('a[href="/home"]');
        if (toHome) toHome.click();
      }, 700);
    }, 200);
  }

  /** 재생 중임을 화면에 작게 표시한다. 목(mock)이라는 사실을 숨기지 않는다. */
  var tag = document.createElement("div");
  tag.style.cssText =
    "position:fixed;top:8px;right:8px;z-index:99999;background:#1E2E4F;color:#fff;" +
    "font:12px/1.4 system-ui;padding:6px 10px;border-radius:8px;opacity:.85;pointer-events:none";
  document.body.appendChild(tag);

  var ticker = setInterval(function () {
    tag.textContent =
      "시연 위치 재생 " +
      Math.min(i + 1, POINTS.length) +
      "/" +
      POINTS.length +
      (i >= POINTS.length - 1 ? " (끝)" : "");
  }, 500);

  window.__tancheonDemo = {
    reset: function () {
      i = 0;
    },
    stop: function () {
      clearInterval(ticker);
      tag.remove();
    },
  };

  console.log("[탄천런 시연] 위치 재생기를 켰습니다. 점 " + POINTS.length + "개 · 약 1분 7초");
})();
